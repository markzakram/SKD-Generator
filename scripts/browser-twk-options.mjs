import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.SKD_PLAYWRIGHT_MODULE ?? 'playwright');
const dir = path.resolve('test-results');
const fixture = JSON.parse(fs.readFileSync(path.join(dir, 'twk-options-tryout-2027.json'), 'utf8'));
const base = process.env.SKD_BROWSER_URL ?? 'http://127.0.0.1:3107';
const browser = await chromium.launch({ headless: true, ...(process.env.SKD_BROWSER_EXECUTABLE ? { executablePath: process.env.SKD_BROWSER_EXECUTABLE } : {}) });
const context = await browser.newContext({ viewport: { width: 1500, height: 1100 }, acceptDownloads: true });
const page = await context.newPage(), errors = [];
page.on('pageerror', (error) => errors.push(error.message));
try {
  const response = await context.request.post(base + '/api/generate', { data: fixture.result.settings });
  assert.equal(response.status(), 200);
  const generated = await response.json();
  assert.equal(generated.audit.ok, true);
  assert.ok(generated.packages[0].questions.every((q) => q.proof.kind === 'local' && q.proof.version === 2));
  assert.deepEqual(generated.packages[0].questions.map((q) => q.options), fixture.result.packages[0].questions.map((q) => q.options), 'API dan generator lokal menyusun opsi yang sama');
  await page.goto(base);
  await page.waitForFunction(() => document.querySelector('.save-status')?.textContent.includes('Tersimpan'));
  await page.locator('input[type=file]').first().setInputFiles(path.join(dir, 'twk-options-tryout-2027.json'));
  await page.locator('.question-card').waitFor();
  const question = fixture.result.packages[0].questions.find((q) => q.topic === 'Nasionalisme');
  await page.getByRole('complementary', { name: 'Antrean soal' }).getByRole('button', { name: new RegExp('^Buka soal ' + question.no + ',') }).click();
  const options = await page.locator('.question-card .options li').allTextContents();
  assert.equal(options.length, 5);
  options.forEach((option, i) => assert.ok(option.includes(question.options[i].text)));
  const source = page.locator('.question-card .source-note');
  assert.match(await source.textContent(), / v2\./);
  await page.screenshot({ path: path.join(dir, 'twk-options-desktop.png') });
  await page.getByRole('button', { name: 'Ganti nomor ini', exact: true }).click();
  await page.waitForFunction((previous) => document.querySelector('.question-card .question-stem')?.textContent !== previous, question.stem);
  assert.match(await source.textContent(), / v2\./);
  const saved = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Cadangan', exact: true }).click();
  const backup = await saved;
  await backup.saveAs(path.join(dir, 'twk-options-browser-backup.json'));
  const latest = JSON.parse(fs.readFileSync(path.join(dir, 'twk-options-browser-backup.json'), 'utf8'));
  assert.ok(latest.result.packages[0].questions.every((q) => q.proof.version === 2));
  assert.notEqual(latest.result.packages[0].questions.find((q) => q.no === question.no).stem, question.stem);
  await page.reload(); await page.locator('.question-card').waitFor();
  assert.match(await source.textContent(), / v2\./);
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: path.join(dir, 'twk-options-mobile.png'), fullPage: true });
  assert.deepEqual(errors, []);
  console.log('PASS: API, opsi TWK v2 pada layar, ganti nomor, cadangan, reload, dan mobile.');
} finally { await browser.close(); }
