import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.SKD_PLAYWRIGHT_MODULE ?? 'playwright');
const dir = path.resolve('test-results');
// npm run verify:siadu prepares a saved workspace with two complete 110-question packages.
const fixture = path.join(dir, 'siadu-fixture.json');
const browser = await chromium.launch({ headless: true, ...(process.env.SKD_BROWSER_EXECUTABLE ? { executablePath: process.env.SKD_BROWSER_EXECUTABLE } : {}) });
const context = await browser.newContext({ viewport: { width: 1600, height: 1000 } });
const page = await context.newPage(), errors = [];
page.on('pageerror', (e) => errors.push(e.message));
const queue = page.getByRole('complementary', { name: 'Antrean soal' });
const modes = queue.getByRole('group', { name: 'Tampilan daftar soal' });
const open = (no) => queue.getByRole('button', { name: new RegExp('^Buka soal ' + no + ',') }).click();
const chosen = (no) => queue.getByRole('checkbox', { name: new RegExp('^Pilih soal ' + no + ' ') });
const current = async (no) => {
  await page.waitForFunction((n) => document.querySelector('.question-card .question-number')?.textContent.trim() === String(n), no);
  assert.equal(await queue.locator('[aria-current=true] .queue-no').textContent(), String(no).padStart(2, '0'));
};
const metrics = () => queue.locator('.queue-list').evaluate((el) => {
  const box = el.getBoundingClientRect();
  const visible = [...el.querySelectorAll('.number-button')].filter((q) => { const r = q.getBoundingClientRect(); return r.top >= box.top && r.bottom <= box.bottom; }).length;
  return { visible, height: el.clientHeight, content: el.scrollHeight, scroll: el.scrollTop };
});
try {
  assert.equal((await page.goto(process.env.SKD_BROWSER_URL ?? 'http://localhost:3000')).status(), 200);
  await page.waitForFunction(() => document.querySelector('.save-status')?.textContent.includes('Tersimpan'));
  await page.locator('input[type=file]').first().setInputFiles(fixture);
  await queue.waitFor();
  assert.equal(await modes.getByRole('button', { name: 'Nomor', exact: true }).getAttribute('aria-pressed'), 'true');
  assert.equal(await queue.locator('.number-button').count(), 110);
  for (const [subtest, count] of [['TWK', 30], ['TIU', 35], ['TKP', 45]]) assert.equal(await queue.getByRole('region', { name: 'Nomor soal ' + subtest }).locator('.number-button').count(), count);
  const overview = await metrics();
  assert.equal(overview.visible, 110, 'Full package fits desktop overview');
  await page.screenshot({ path: path.join(dir, 'queue-desktop.png') });
  await open(110); await current(110);
  await page.keyboard.press('k'); await current(109);
  await modes.getByRole('button', { name: 'Rinci', exact: true }).click();
  assert.equal(await queue.locator('.queue-stem').count(), 110);
  const detailed = await metrics();
  assert.ok(detailed.scroll > 0, 'Active question scrolled into detailed list');
  assert.ok(detailed.content > overview.content * 5, 'Overview materially reduces scrolling');
  await modes.getByRole('button', { name: 'Nomor', exact: true }).click();
  await current(109);
  await queue.getByLabel('Cari soal', { exact: true }).fill('52');
  assert.equal(await queue.locator('.number-button').count(), 1);
  await open(52); await current(52);
  await queue.getByLabel('Filter subtes').selectOption('TWK');
  await queue.getByText('Tidak ada soal sesuai filter.', { exact: true }).waitFor();
  await queue.getByRole('button', { name: 'Hapus filter', exact: true }).click();
  assert.equal(await queue.locator('.number-button').count(), 110);
  await queue.getByRole('button', { name: 'Pilih nomor', exact: true }).click();
  await chosen(2).check();
  await queue.getByLabel('Filter subtes').selectOption('TKP');
  await chosen(66).check();
  await queue.getByRole('button', { name: 'Ganti nomor terpilih (2)' }).waitFor();
  await queue.getByRole('button', { name: 'Selesai pilih', exact: true }).click();
  await modes.getByRole('button', { name: 'Rinci', exact: true }).click();
  assert.equal(await queue.getByLabel('Pilih nomor 66 untuk diganti').isChecked(), true);
  await queue.getByLabel('Filter subtes').selectOption('all');
  assert.equal(await queue.getByLabel('Pilih nomor 2 untuk diganti').isChecked(), true);
  await queue.getByRole('button', { name: 'Ganti nomor terpilih (2)' }).click();
  await page.locator('.notice-message').filter({ hasText: '2 nomor diganti (2, 66)' }).waitFor();
  assert.equal(await queue.locator('input[type=checkbox]:checked').count(), 0);
  await modes.getByRole('button', { name: 'Nomor', exact: true }).click();
  await queue.getByRole('button', { name: 'Pilih nomor', exact: true }).click();
  await queue.getByLabel('Filter subtes').selectOption('TWK');
  await queue.getByRole('button', { name: 'Pilih semua', exact: true }).click();
  await queue.getByRole('button', { name: 'Ganti nomor terpilih (30)' }).waitFor();
  await queue.getByRole('button', { name: 'Kosongkan', exact: true }).click();
  assert.ok(await queue.getByRole('button', { name: 'Ganti nomor terpilih (0)' }).isDisabled());
  // Native checkbox keyboard operation remains available on a compact number tile.
  await chosen(3).focus(); await page.keyboard.press('Space');
  assert.equal(await chosen(3).isChecked(), true);
  await queue.getByRole('button', { name: 'Kosongkan', exact: true }).click();
  await queue.getByRole('button', { name: 'Selesai pilih', exact: true }).click();
  await queue.getByLabel('Filter subtes').selectOption('all');
  await page.setViewportSize({ width: 1366, height: 768 });
  await open(1);
  const laptop = await metrics();
  assert.ok(laptop.content < laptop.height * 2, 'Short laptop screen needs at most one extra panel scroll');
  await page.screenshot({ path: path.join(dir, 'queue-laptop.png') });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'No mobile horizontal overflow');
  await open(110); await current(110);
  await queue.getByLabel('Cari soal', { exact: true }).fill('31');
  await open(31); await current(31);
  await queue.getByLabel('Cari soal', { exact: true }).fill('');
  await page.screenshot({ path: path.join(dir, 'queue-mobile.png'), fullPage: true });
  await queue.screenshot({ path: path.join(dir, 'queue-mobile-panel.png') });
  // J/K scrolls only the queue, never the page while the reader is further down on mobile.
  await page.locator('.question-card').scrollIntoViewIfNeeded();
  await page.locator('.question-card .question-number').click();
  const scroll = await page.evaluate(() => window.scrollY);
  await page.keyboard.press('j'); await current(32);
  assert.equal(await page.evaluate(() => window.scrollY), scroll);
  assert.deepEqual(errors, []);
  const report = { status: 'PASS', overview, detailed, laptop, navigation: true, filters: true, selectionAcrossViews: true, replaceSelected: true, keyboard: true, mobileOverflow: false, errors };
  fs.writeFileSync(path.join(dir, 'browser-queue-report.json'), JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report));
} catch (error) {
  await page.screenshot({ path: path.join(dir, 'queue-failure.png'), fullPage: true });
  console.log(JSON.stringify({ errors, alerts: await page.locator('[role=alert]').allTextContents() }));
  throw error;
} finally { await browser.close(); }
