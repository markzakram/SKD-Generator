import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.SKD_PLAYWRIGHT_MODULE ?? 'playwright');
const directory = path.resolve('test-results');
fs.mkdirSync(directory, { recursive: true });
const browser = await chromium.launch({ headless: true, ...(process.env.SKD_BROWSER_EXECUTABLE ? { executablePath: process.env.SKD_BROWSER_EXECUTABLE } : {}) });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
const page = await context.newPage();
const errors = [];
page.on('pageerror', (error) => errors.push(error.message));
const base = process.env.SKD_BROWSER_URL ?? 'http://127.0.0.1:3107';
try {
  const response = await page.goto(base);
  assert.equal(response.status(), 200);
  await page.waitForFunction(() => document.querySelectorAll('.question-card').length === 110);
  await page.screenshot({ path: path.join(directory, 'desktop.png') });
  await page.getByRole('button', { name: 'Bank & cakupan' }).click();
  assert.ok((await page.locator('.bank-overview').textContent()).includes('117'));
  await page.getByRole('button', { name: 'Panduan penggunaan' }).click();
  assert.equal(await page.locator('.guide-step').count(), 4);
  await page.getByRole('button', { name: 'Generator soal', exact: true }).click();
  await page.locator('.competency-card').nth(2).click();
  await page.getByLabel('Soal per paket', { exact: true }).fill('8');
  await page.getByLabel('Verbal', { exact: true }).uncheck();
  await page.getByLabel('Numerik', { exact: true }).uncheck();
  await page.getByRole('button', { name: 'Buat paket soal', exact: true }).click();
  await page.waitForFunction(() => document.querySelectorAll('.question-card').length === 8);
  assert.equal(await page.locator('.visual-options').count(), 8);
  await page.locator('.subtopic-control summary').click();
  await page.locator('.subtopic-list label').filter({ hasText: 'Matriks 3 × 3' }).locator('input').check();
  await page.getByRole('button', { name: 'Buat paket soal', exact: true }).click();
  await page.waitForFunction(() => document.querySelectorAll('.question-card').length === 8 &&
    [...document.querySelectorAll('.question-meta')].every((element) => element.textContent.includes('Matriks')));
  await page.getByRole('button', { name: 'Gunakan semua submateri', exact: true }).click();
  await page.locator('.subtopic-control summary').click();
  await page.getByRole('button', { name: 'Buat paket soal', exact: true }).click();
  await page.waitForFunction(() => document.querySelectorAll('.visual-matriks').length < 8);
  await page.getByLabel('Tampilkan kunci', { exact: true }).check();
  assert.equal(await page.locator('.correct-option').count(), 8);
  await page.getByLabel('Cari soal dalam paket').fill('___tidak_ada___');
  assert.equal(await page.locator('.question-card').count(), 0);
  await page.getByLabel('Cari soal dalam paket').fill('');
  const save = async (filename) => {
    const promise = page.waitForEvent('download', { timeout: 60000 });
    await page.locator('.export-dialog .primary-button').click();
    const download = await promise;
    await download.saveAs(path.join(directory, filename));
    await page.waitForFunction(() => !document.querySelector('.export-dialog .primary-button')?.disabled);
    return fs.readFileSync(path.join(directory, filename));
  };
  await page.getByRole('button', { name: 'Unduh paket', exact: true }).click();
  await page.getByLabel('Isi dokumen').selectOption('soal');
  const pdf = await save('soal-figural.pdf');
  assert.equal(pdf.subarray(0, 5).toString(), '%PDF-');
  await page.locator('.format-button').nth(1).click();
  await page.getByLabel('Isi dokumen').selectOption('pembahasan');
  const word = await save('pembahasan-figural.docx');
  const { unzipSync } = require('fflate');
  const parts = unzipSync(word);
  assert.ok(parts['word/document.xml']);
  assert.equal(Object.keys(parts).filter((name) => name.startsWith('word/media/') && name.endsWith('.png')).length, 8);
  await page.locator('.format-button').nth(2).click();
  const csv = await save('bank-figural.csv');
  assert.ok(csv.toString().includes('Stimulus JSON'));
  await page.locator('.format-button').nth(3).click();
  const data = JSON.parse((await save('paket-figural.json')).toString());
  assert.equal(data.packages[0].questions.length, 8);
  assert.ok(data.packages[0].questions.every((question) => question.visual));
  await page.locator('.format-button').nth(0).click();
  await page.getByLabel('Pisahkan per paket dalam ZIP').check();
  const zip = await save('paket-pdf.zip');
  assert.equal(Object.keys(unzipSync(zip)).length, 1);
  await page.getByLabel('Tutup dialog ekspor').click();
  await page.reload();
  await page.waitForFunction(() => document.querySelectorAll('.question-card').length === 8);
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'Layout mobile melebar di luar viewport.');
  await page.screenshot({ path: path.join(directory, 'mobile.png') });
  const valid = await context.request.post(base + '/api/generate', { data: { mode: 'TWK', count: 5, packages: 1 } });
  assert.equal(valid.status(), 200); assert.equal((await valid.json()).audit.checked, 5);
  const invalid = await context.request.post(base + '/api/generate', { data: { mode: 'INVALID' } });
  assert.equal(invalid.status(), 400);
  assert.deepEqual(errors, []);
  fs.writeFileSync(path.join(directory, 'browser-report.json'), JSON.stringify({ status: 'PASS', exports: 5, mobileOverflow: false, browserErrors: errors }, null, 2));
  console.log(JSON.stringify({ status: 'PASS', exports: 5, screenshots: ['desktop.png', 'mobile.png'], errors }));
} finally { await browser.close(); }
