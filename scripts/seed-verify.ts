import assert from 'node:assert/strict';
import fs from 'node:fs';
import { DEFAULT_SETTINGS } from '../lib/config';
import { generate, normalizeSettings } from '../lib/generate';
import { compareSeeds, contentKey, scanSummary, sequenceSeeds, checkScanBudget, questionVariables, type SeedRun } from '../lib/seed-analysis';
import { variationSpace } from '../lib/variation-space';
import { LOCAL_MODELS, LOCAL_RECIPES, renderLocal } from '../lib/local';
import type { Question } from '../lib/types';

const question = (stem = 'Nilai \\(x+2\\) adalah …'): Question => ({ id: 'q', no: 1, subtest: 'TIU', topic: 'Numerik', subtopic: 'Uji hitung', difficulty: 'sedang', family: 'hitung', stem,
  options: [3, 4, 5, 6, 7].map((n, i) => ({ text: String(n), score: i === 0 ? 5 : 0, reason: '' })), answer: 0, explanation: 'Hitung sesuai persamaan.', source: 'uji', origin: 'pola', proof: { kind: 'manual', note: 'Uji comparator' } });
const run = (questions: Question[], seed = 'A'): SeedRun => ({ seed, packages: [{ id: 'SKD-01', seed, mode: 'TIU', duration: 100, questions }] });
const q = question();
const reorder = { ...structuredClone(q), id: 'new-id', no: 20, options: [...q.options].reverse(), answer: 4 };
assert.equal(contentKey(q), contentKey(reorder));
assert.equal(compareSeeds(run([q]), run([reorder], 'B')).counts.order, 1);
assert.equal(compareSeeds(run([q]), run([reorder], 'B')).rows[0].moved, true);
assert.notEqual(contentKey(q), contentKey(question('Nilai \\(x-2\\) adalah …')), 'Operator matematika tidak boleh dihapus');
assert.notEqual(contentKey(question('1,5')), contentKey(question('15')), 'Desimal tidak boleh digabung');
const rerank = structuredClone(q); [rerank.options[0].score, rerank.options[1].score] = [0, 5]; rerank.answer = 1;
assert.notEqual(contentKey(q), contentKey(rerank));
assert.equal(compareSeeds(run([q]), run([rerank])).counts.variant, 1);
assert.equal(compareSeeds(run([q]), run([{ ...q, explanation: 'Penjelasan yang disunting.' }])).counts.explanation, 1);
const q2 = question('Nilai \\(x+3\\) adalah …');
const exactFirst = compareSeeds(run([q, q2]), run([question('Nilai \\(x+9\\) adalah …'), structuredClone(q)], 'B'));
assert.equal(exactFirst.rows[1].a?.q.stem, q.stem, 'Pasangan yang persis sama harus dicadangkan sebelum memasangkan variasi');
assert.equal(exactFirst.shared, 1);
const duplicates = compareSeeds(run([q]), run([q, q]));
assert.equal(duplicates.shared, 1, 'Pencocokan multiset: satu soal A hanya boleh dipakai sekali');
assert.equal(duplicates.counts.different, 1);
assert.equal(compareSeeds(run([q, q2]), run([q])).onlyA.length, 1);
const model = LOCAL_MODELS.find((m) => m.states.length > 1)!;
const localA = renderLocal({ kind: 'local', version: 1, model: model.id, context: 0, state: 0, order: [0, 1, 2, 3, 4] });
const localB = renderLocal({ kind: 'local', version: 1, model: model.id, context: 0, state: 1, order: [0, 1, 2, 3, 4] });
assert.equal(compareSeeds(run([localA]), run([localB])).counts.variant, 1);
assert.ok(compareSeeds(run([localA]), run([localB])).rows[0].changed.includes('Kondisi keputusan'));
assert.notEqual(questionVariables(localA)['Fakta penentu'], questionVariables(localB)['Fakta penentu']);
assert.deepEqual(sequenceSeeds('1001', 3), ['1001', '1002', '1003']);
assert.equal(new Set(sequenceSeeds('x'.repeat(100), 20)).size, 20);
assert.ok(sequenceSeeds('x'.repeat(100), 20).every((s) => s.length <= 100));
assert.throws(() => sequenceSeeds('', 5));
assert.throws(() => checkScanBudget({ ...DEFAULT_SETTINGS, packages: 50 }, 20));
const sample = scanSummary([run([q]), run([reorder], 'B'), run([q2], 'C')]);
assert.deepEqual(sample.rows.map((row) => row.added), [1, 0, 1]); assert.equal(sample.unique, 2);
const settings = normalizeSettings({ ...DEFAULT_SETTINGS, profile: 'tryout-2027', twkSource: 'new', tkpSource: 'new', tiuSource: 'variation', seed: '1001' });
const before = JSON.stringify(settings), generatedA = generate(settings), reproduced = generate(settings), generatedB = generate({ ...settings, seed: '1002' });
assert.equal(JSON.stringify(settings), before);
assert.deepEqual(generatedA, reproduced);
const figural = generatedA[0].questions.find((item) => item.visual)!;
assert.equal(contentKey(figural), contentKey({ ...figural, options: [...figural.options].reverse(), answer: 4 - figural.answer }), 'Pengacakan gambar opsi bukan isi baru');
const matrix = generatedA[0].questions.find((item) => item.subtopic === 'Matriks Deret' && item.table && !item.table.headers.length);
if (matrix?.table) assert.equal(contentKey(matrix), contentKey({ ...matrix, table: { headers: matrix.table.rows[0], rows: matrix.table.rows.slice(1) } }), 'Header angka lama dinormalisasi menjadi data');
const equal = compareSeeds({ seed: '1001', packages: generatedA }, { seed: '1001', packages: reproduced });
assert.equal(equal.overlap, 100); assert.equal(equal.counts.same, 110);
const different = compareSeeds({ seed: '1001', packages: generatedA }, { seed: '1002', packages: generatedB });
assert.ok(different.shared < 110); assert.ok(different.rows.every((row) => !row.a || row.a.q.subtest === row.b.q.subtest));
assert.equal(Object.values(different.counts).reduce((a, b) => a + b, 0), 110);
const catalog = variationSpace(settings);
const expectedLocal = LOCAL_RECIPES.filter((r) => ['TWK', 'TKP'].includes(r.subtest)).length;
assert.equal(catalog.filter((row) => row.kind === 'local').reduce((n, row) => n + (row.size ?? 0), 0), expectedLocal);
assert.ok(catalog.filter((row) => row.kind === 'parameter').every((row) => row.size === null));
const twkBank = variationSpace({ ...settings, mode: 'TWK', count: 30, twkSource: 'accepted' });
assert.ok(twkBank.every((row) => row.kind === 'bank' && row.subtest === 'TWK'));
const restricted = variationSpace({ ...settings, mode: 'TKP', count: 3, topics: ['Pelayanan Publik'] });
assert.ok(restricted.every((row) => row.subtest === 'TKP' && row.topic === 'Pelayanan Publik'));
fs.mkdirSync('test-results', { recursive: true });
fs.writeFileSync('test-results/seed-analysis.json', JSON.stringify({ seedA: '1001', seedB: '1002', same: equal.counts, different: different.counts, overlap: different.overlap, sources: catalog }, null, 2));
console.log('LULUS: seed identik, pengacakan opsi, pindah nomor, tanda matematika, bobot, kondisi lokal, pencocokan multiset, sampel unik, katalog/filter, dan determinisme 110 soal.');
console.log(JSON.stringify({ overlap: different.overlap, counts: different.counts, localCombinations: expectedLocal }));
