import assert from 'node:assert/strict';
import fs from 'node:fs';
import rawBank from '../data/tryout-reference.json';
import { academicText } from '../lib/academic-format';
import { explanationOf, parseExplanation } from '../lib/explanation';
import { questionBlocks } from '../lib/export';
import { createWorkspace } from '../lib/quality';
import { DEFAULT_SETTINGS } from '../lib/config';
import { richRuns, stripMarks } from '../lib/richtext';
import { mathParts } from '../lib/math';
import type { BankItem, Question } from '../lib/types';

const raw = rawBank as BankItem[];
const source = (id: string): Question => ({ ...raw.find(q => q.id === id)!, id, no: 1, family: id, origin: 'referensi', proof: { kind: 'manual', note: 'Contoh diterima' } });
const silo = source('tryout-ref-09-14'), seating = source('tryout-ref-11-02');
assert.ok(!silo.explanation.includes('**'), 'Regression input must be the old unformatted question');
const restored = explanationOf(silo);
assert.match(restored, /\*\*Terpenuhinya standar kandungan kimia\*\*/);
assert.match(restored, /\*\*perolehan status aman untuk saluran pembuangan\*\*/);
assert.equal(stripMarks(restored), silo.explanation, 'Restoring bold must preserve wording and logic');
assert.equal(explanationOf({ ...silo, explanation: restored }), restored, 'Formatting is idempotent');
const edit = silo.explanation.replace('Premis 1: Terpenuhinya standar kandungan kimia', 'Premis 1: Hasil suntingan akademik');
assert.ok(explanationOf({ ...silo, explanation: edit }).startsWith('Premis 1: Hasil suntingan akademik'), 'Do not overwrite edits');
assert.equal(academicText({ provenance: { ...silo.provenance!, sourceHash: 'different' } }, silo.explanation), silo.explanation, 'Do not apply formatting from another source revision');
const table = parseExplanation(explanationOf(seating))?.find(b => b.k === 'table');
assert.ok(table?.k === 'table'); assert.deepEqual(table.headers.map(stripMarks), ['Baris', 'Kiri', 'Kanan']);
assert.deepEqual(table.rows.map(row => row.map(stripMarks)), [['1', 'Gani', 'Hira'], ['2', 'Intan', 'Joko'], ['3', 'Kila', 'Luki'], ['4', 'Mira', 'Nando']]);
assert.equal(parseExplanation('Prosa A | B saja.'), null, 'One ordinary prose line is not a table');
assert.ok(!parseExplanation('\\( |x| + |y| \\)')?.some(b => b.k === 'table'), 'Absolute values are not table rows');
const bare = parseExplanation('Baris | Kiri | Kanan\n1 | Gani | Hira\n2 | Intan | Joko');
assert.equal(bare?.[0].k, 'table');
const matrix = parseExplanation('| 1 | 2 | 3 |\n| 4 | 5 | 6 |');
assert.ok(matrix?.[0].k === 'table' && matrix[0].headers.length === 0);
assert.ok(mathParts('¬p ∧ ¬q').some(p => p.kind === 'math' && p.value.includes('\\neg')));
let count = 0;
for (const item of raw.filter(q => q.provenance?.lesson === 'Silogisme')) {
  const text = academicText(item, item.explanation);
  assert.ok(richRuns(text).some(run => run.bold), item.id + ' must retain original emphasis'); count++;
}
const stimulusTable = questionBlocks({ ...seating, table: { headers: ['Nama', 'Nilai'], rows: [['Gani', '8']] } }, 'soal', null).head;
assert.ok(stimulusTable.some(b => b.kind === 'table'), 'PDF stimulus tables must have real cells');
for (const q of [silo, seating]) for (const b of [...questionBlocks(q, 'pembahasan', null).head, ...questionBlocks(q, 'pembahasan', null).tail]) if (b.kind === 'text' || b.kind === 'table') assert.equal(b.size, 12);
const academic = JSON.parse(fs.readFileSync('test-results/academic-fixture.json', 'utf8'));
const examples: Question[] = academic.result.packages[0].questions;
const questions = [silo, seating, source('tryout-ref-09-01'), ...examples.filter(q => ['WOWO', 'VDW', 'JKW'].some(word => q.explanation.includes(word))).slice(0, 2), examples[7], examples[9], examples[11]].map((q, i) => ({ ...q, no: i + 1, binding: undefined }));
const settings = { ...DEFAULT_SETTINGS, title: 'QC format akademik — contoh pengguna', packages: 1, twk: 0, tiu: questions.length - 1, tkp: 1 };
const result = { settings, packages: [{ id: 'QC-AKADEMIK', seed: 'format-source-regression', mode: 'SKD' as const, duration: 100, questions }], audit: { ok: true, checked: questions.length, errors: [], duplicateCount: 0, keyDistribution: [0,0,0,0,0] }, elapsed: 0 };
fs.writeFileSync('test-results/academic-regression-fixture.json', JSON.stringify(createWorkspace(result)));
console.log(`PASS: original bold on ${count} syllogisms; exact seating table, saved workspaces, edited text, numeric matrices, uniform 12 pt, and PDF table blocks.`);
