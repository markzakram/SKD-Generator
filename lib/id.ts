// crypto.randomUUID hanya ada di konteks aman (HTTPS atau localhost) dan peramban yang cukup baru. Aplikasi yang dibuka lewat alamat jaringan
// (mis. http://192.168.1.5:3000) tidak punya fungsi itu, jadi buat UUID v4 sendiri dari getRandomValues, yang tetap tersedia di sana.
export function newId(): string {
  const c = globalThis.crypto;
  if (typeof c?.randomUUID === 'function') return c.randomUUID();
  const b = new Uint8Array(16);
  if (typeof c?.getRandomValues === 'function') c.getRandomValues(b);
  else for (let i = 0; i < 16; i++) b[i] = Math.floor(Math.random() * 256);
  b[6] = (b[6] & 0x0f) | 0x40; b[8] = (b[8] & 0x3f) | 0x80;
  const h = Array.from(b, (x) => x.toString(16).padStart(2, '0')).join('');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20)}`;
}
