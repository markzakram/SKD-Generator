// ---- Rumus blueprint (bentuk LaTeX yang dipakai pembahasan) -> pohon logika ------------------------------------------------------------------------------------
const literal = (text: string): Logic => {
  const m = /^(\\neg )?([pqrst])$/.exec(text.trim());
  if (!m) throw new Error('Literal contoh tidak dikenal: ' + text);
  return m[1] ? not(variable(m[2])) : variable(m[2]);
};
export function logicFromTex(tex: string): Logic {
  const negated = /^\\neg \((.+)\)$/.exec(tex.trim());
  if (negated) return not(logicFromTex(negated[1]));
  const op = / \\(to|lor|land) /.exec(tex);
  if (!op) return literal(tex);
  const [left, right] = tex.split(op[0]);
  return { op: op[1] === 'to' ? 'implies' : op[1] === 'lor' ? 'or' : 'and', left: literal(left), right: literal(right) };
}

