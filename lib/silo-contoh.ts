export const contohOf = (chapter: NarasiChapter) => CONTOH_NARASI.filter((item) => item.chapter === chapter);
// Keluarga modus contoh (aturan penentu: lib/silo-spec.ts) dari hukum tiap langkah; dipakai perencana paket (lib/silo-rencana.ts) dan pemeriksa keberagaman.
const LAW_ID: Record<string, LawId | 'tds'> = { 'Modus Ponens': 'mp', 'Modus Tollens': 'mt', 'hukum Silogisme': 'sk', 'Silogisme Disjungtif': 'sd', TDS: 'tds' };
export const keluargaOfContoh = (item: Contoh): Keluarga => keluargaOfLaws(item.laws.map((law) => LAW_ID[law] ?? (() => { throw new Error('Hukum contoh tidak dikenal: ' + law); })()), false);
// Keluarga butir dari kodenya: contoh blueprint (N2-01 sampai N3-11) atau kode katalog pembangkit; undefined bila kode tidak dikenal.
export const keluargaOfCode = (code: string): Keluarga | undefined => { const item = CONTOH_NARASI.find((c) => c.code === code); return item ? keluargaOfContoh(item) : keluargaOfCatalogCode(code); };
// Contoh ke-`ordinal` yang dipakai pada satu pembuatan paket (urutan contoh diacak menurut seed dengan pengacak tersendiri, sehingga tidak menggeser keacakan butir lain);
// undefined bila semua contoh chapter itu sudah terpakai dan pembangkit yang harus mengisi kekurangannya.
export function contohAt(chapter: NarasiChapter, seed: string, ordinal: number): Contoh | undefined {
  const list = contohOf(chapter);
  return ordinal >= 0 && ordinal < list.length ? rng(seed + '|contoh-narasi|' + chapter).shuffle(list)[ordinal] : undefined;
}
function reasonOf(item: Contoh): string {
  const laws = item.laws.filter((law) => law !== 'TDS'), n = item.premises.length === 2 ? 'dua' : 'tiga', tds = item.notes[item.answer].symbol === null;
  const chain = laws.length === 2 && laws[0] === laws[1] ? 'dua langkah ' + laws[0] : laws.join(' lalu ');
  const text = tds ? (laws.length ? 'Menggabungkan ' + n + ' premis lewat ' + chain + ' lalu memastikan bahwa pernyataan yang ditanyakan tidak dapat disimpulkan' :
    'Memastikan bahwa dua premis tidak memenuhi syarat Modus Ponens, Modus Tollens, maupun silogisme sehingga pernyataan yang ditanyakan tidak dapat disimpulkan') :
    n === 'dua' ? 'Menerapkan ' + chain + ' pada dua premis' : 'Menggabungkan tiga premis lewat ' + chain;
  return text + '; kata kunci proposisi diambil dari kalimat panjang dan label tidak dinaikkan hanya karena narasi lebih panjang.';
}
// Butir jadi dari satu contoh. Urutan opsi diacak dengan `r` (pengacak butir), `ref` tiap opsi = nomor urut hasil acak pada butir ini, dan analisis opsi memakai {opsi:ref}.
export function contohBuild(item: Contoh, r: Rng): LogikaBuild {
  const P = item.premiseTex.map(logicFromTex), n = P.length, order = r.shuffle([0, 1, 2, 3, 4]);
  const options: LogikaOption[] = order.map((k, ref) => {
    const note = item.notes[k], logic = note.symbol === null ? undefined : logicFromTex(note.symbol);
    const status: LogikaStatus = k === item.answer ? 'pasti' : logic && !entails(P, [not(logic)])[0] ? 'belum' : 'bertentangan';
    return { text: item.options[k], reason: note.reason, status, ref, ...(logic ? { logic } : {}), ...(note.error ? { error: note.error } : {}) };
  });
  const lines = [...item.quoted.map((text, i) => 'Premis ' + (i + 1) + ': ' + text), '', ...item.defs.map(([name, text]) => inline(name) + ': ' + text), '', ...item.steps, '',
    ...analysisBlock(order.map((k, ref) => ({ ref, text: item.options[k], symbol: item.notes[k].symbol, reason: item.notes[k].reason, key: k === item.answer })), item.extra ? [{ name: item.extra[0], text: item.extra[1] }] : [])];
  const implications = item.premiseTex.filter((tex) => tex.includes('\\to')).length, forward = item.forward ?? [];
  const model: Model = { kind: 'syllogism', premises: P, options: options.map((o) => ({ text: o.text, ...(o.logic ? { logic: o.logic } : {}) })), code: item.code, chapter: item.chapter,
    errors: options.map((o) => o.error ?? null), narrative: { implications, reversed: forward.length, forward } };
  return { stem: item.premises.join(' ') + '\n' + item.question, options, answer: order.indexOf(item.answer), explanation: lines.join('\n'), model, bloom: n === 2 ? 'C3' : 'C4', code: item.code, chapter: item.chapter,
    reversed: forward.length, implications, difficultyReason: reasonOf(item), source: 'Contoh ' + item.no + ' (' + item.code + ') pada Blueprint Silogisme Tanpa Logika Kuantor, Bagian B (tulisan tim akademik).' };
}
